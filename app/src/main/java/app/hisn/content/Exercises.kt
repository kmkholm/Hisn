/** خطوة داخل التمرين. الأنواع المختلفة تجعل التمرين تفاعليًا لا نصًّا يُقرأ. */
sealed interface Step {
    /** تعليمة تُقرأ ثم يُتابع. */
    data class Say(val text: String, val hint: String? = null) : Step

    /** مؤقّت صامت — الجلوس مع الشعور دون فعل هو التمرين نفسه. */
    data class Hold(val seconds: Int, val text: String) : Step

    /** تنفّس موجّه بأطوار محددة. */
    data class Breath(
        val cycles: Int,
        val inhale: Int,
        val hold: Int,
        val exhale: Int,
        val text: String
    ) : Step

    /** إدخال نصي من المستخدم — يبقى على الجهاز. */
    data class Ask(val prompt: String, val placeholder: String) : Step

    /** قياس من 0 إلى 10، يُستخدم لقياس أثر التمرين قبل/بعد. */
    data class Scale(val prompt: String, val isBefore: Boolean = false, val isAfter: Boolean = false) : Step
}

