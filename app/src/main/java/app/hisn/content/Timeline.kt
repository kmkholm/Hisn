enum class Evidence(val label: String, val note: String) {
    STRONG("مثبت", "مدعوم بأدلة بشرية متسقة"),
    MODERATE("مرجّح", "مدعوم نظريًا وبأدلة غير مباشرة أو محدودة"),
    REPORTED("ملاحظ بلا دليل", "شائع في التقارير الذاتية، بلا دراسات محكّمة")
}

data class TimelineItem(
    val text: String,
    val evidence: Evidence
)

data class TimelineWindow(
    val range: IntRange,
    val title: String,
    val summary: String,
    val items: List<TimelineItem>
) {
    val label: String
        get() = if (range.first == range.last) "اليوم ${range.first}"
        else "الأيام ${range.first}–${range.last}"
}

data class Myth(
    val claim: String,
    val verdict: String,
    val truth: String
)

